import { z } from 'zod';

export const get_analytics_project_events = {
  name: 'get_analytics_project_events',
  description: 'Get events',
  inputSchema: z.object({
    projectId: z.number().describe('The ID of the project'),
    startDate: z.iso
      .date()
      .describe('The start date for the analytics (YYYY-MM-DD)'),
    endDate: z.iso
      .date()
      .describe('The end date for the analytics (YYYY-MM-DD)'),
  }),
  outputSchema: z.object({
    data: z
      .array(
        z.object({
          eventName: z.string().describe('The name of the event'),
          eventCount: z
            .number()
            .describe('The number of times the event occurred'),
          totalUsers: z
            .number()
            .describe('Total number of users who triggered the event'),
          activeUsers: z
            .number()
            .describe('Number of active users who triggered the event'),
          totalRevenue: z
            .number()
            .describe('Total revenue generated by the event'),
          eventCountPerUser: z
            .number()
            .describe('The average number of events per user'),
        })
      )
      .describe('An array of events and their metrics'),
  }),
  method: 'get',
  path: '/v1/analytics/{projectId}/events',
};
